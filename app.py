"""Fresh Department Analytics: the dashboard.

    streamlit run app.py

Four pages, in the order a department manager asks the questions. All figures
come from dashboard/measures.py, which the tests pin to the published numbers.
"""

from __future__ import annotations

import pandas as pd
import streamlit as st

from dashboard import charts, measures as m
from dashboard.model import CHANGED, CHANGE_DATE, apply_filters, load

st.set_page_config(page_title="Fresh Department Analytics", layout="wide")

st.markdown("""
<style>
.block-container {padding-top: 2.2rem; padding-bottom: 2rem; max-width: 1400px;}
div[data-testid="stMetric"] {background: #ffffff; border: 1px solid #e1e0d9;
    border-radius: 8px; padding: 14px 16px;}
div[data-testid="stMetricLabel"] p {color: #52514e; font-size: 0.82rem;}
div[data-testid="stMetricValue"] {font-size: 1.55rem;}
div[data-testid="stVegaLiteChart"] {background: #ffffff; border: 1px solid #e1e0d9;
    border-radius: 8px; overflow: hidden; box-sizing: border-box;}
</style>
""", unsafe_allow_html=True)


@st.cache_data
def get_model():
    return load()


def money(value: float) -> str:
    return f"${value:,.0f}"


def signed_money(value: float) -> str:
    return f"{'-' if value < 0 else '+'}${abs(value):,.0f}"


def pct(value: float, signed: bool = False) -> str:
    return f"{value:+.2%}" if signed else f"{value:.2%}"


def points(value: float) -> str:
    return f"{value * 100:+.2f} pts"


def cards(items: list[tuple[str, str, str | None]]) -> None:
    for column, (label, value, note) in zip(st.columns(len(items)), items):
        column.metric(label, value, help=note)


def show(chart) -> None:
    st.altair_chart(chart, width="stretch")


def show_table(df: pd.DataFrame, percent: list[str] = (), dollars: list[str] = (),
               signed_points: list[str] = (), signed_percent: list[str] = (),
               signed_dollars: list[str] = ()) -> None:
    """A table view of the page, so nothing depends on reading a chart."""
    fmt = {col: "{:.2%}" for col in percent}
    fmt |= {col: "${:,.0f}" for col in dollars}
    fmt |= {col: "{:+.2%}" for col in signed_percent}
    fmt |= {col: signed_money for col in signed_dollars}
    fmt |= {col: (lambda v: f"{round(v * 100, 2) + 0:+.2f} pts") for col in signed_points}
    st.dataframe(df.style.format(fmt), hide_index=True, width="stretch")


# ------------------------------------------------------------------ filters

model = get_model()
first, last = model.date.Date.min().date(), model.date.Date.max().date()

with st.sidebar:
    st.header("Filters")
    years = ["All"] + sorted(model.date.FinancialYear.unique())
    year = st.selectbox("Financial year", years)
    if year == "All":
        lo, hi = first, last
    else:
        in_year = model.date[model.date.FinancialYear == year].Date
        lo, hi = in_year.min().date(), in_year.max().date()
    picked = st.date_input("Date range", (lo, hi), min_value=first, max_value=last)
    start, end = picked if len(picked) == 2 else (lo, hi)
    subs = st.multiselect("Sub-department", model.sub_departments,
                          placeholder="All sub-departments")
    st.caption("Synthetic data, generated by `scripts/generate_data.py`. "
               "No employer data or real trading figures.")

dated = apply_filters(model, start, end)                 # dates only: the whole department
scoped = apply_filters(model, start, end, subs)          # dates and sub-departments

st.title("Fresh Department Analytics")
scope = ", ".join(subs) if subs else "All sub-departments"
st.caption(f"{scope} · {pd.Timestamp(start):%d %b %Y} to {pd.Timestamp(end):%d %b %Y} · "
           "synthetic data for one supermarket fresh department")

if scoped.sales.empty:
    st.warning("No sales in this selection. Widen the date range.")
    st.stop()

dept_sales = float(dated.sales.NetSales.sum())
head = m.headline(scoped, department_sales=dept_sales)
week = m.weekly(scoped, department_sales=m.department_sales_by_week(dated))

overview, waste, labour, change = st.tabs(
    ["Overview", "Margin and waste", "Labour and roster", "The ordering change"])

# ----------------------------------------------------------------- overview

with overview:
    cards([
        ("Net sales", money(head["Net Sales"]), None),
        ("Trading margin %", pct(head["Trading Margin %"]),
         "Gross margin after waste and markdown."),
        ("Waste % of sales", pct(head["Waste % of Sales"]), None),
        ("Labour % of sales", pct(head["Labour % of Sales"]),
         "Whole department. Labour is not recorded by sub-department."),
        ("Sales vs budget", pct(head["Sales vs Budget %"], signed=True), None),
    ])
    left, right = st.columns([3, 2])
    with left:
        show(charts.sales_vs_budget(week))
    with right:
        show(charts.margins(week))
    by_sub = m.by_sub_department(scoped)
    left, right = st.columns([2, 3])
    with left:
        show(charts.trading_margin_by_sub_department(by_sub))
    with right:
        show_table(
            by_sub[["SubDepartment", "Net Sales", "Gross Margin %", "Waste % of Sales",
                    "Markdown % of Sales", "Trading Margin %"]]
            .rename(columns={"SubDepartment": "Sub-department", "Net Sales": "Net sales",
                             "Gross Margin %": "Gross margin", "Waste % of Sales": "Waste",
                             "Markdown % of Sales": "Markdown",
                             "Trading Margin %": "Trading margin"}),
            ["Gross margin", "Waste", "Markdown", "Trading margin"], ["Net sales"])
    gap = head["Gross Margin %"] - head["Trading Margin %"]
    st.caption(f"{gap * 100:.2f} points of margin sit between the gross number and the trading "
               "number. Ordering, rotation and markdown timing move all of it.")

# --------------------------------------------------------- margin and waste

with waste:
    cards([
        ("Waste cost", money(head["Waste Cost"]), None),
        ("Waste % of sales", pct(head["Waste % of Sales"]), None),
        ("Markdown % of sales", pct(head["Markdown % of Sales"]), None),
        ("Waste vs budget", signed_money(head["Waste vs Budget"]),
         "Waste cost less the waste budget. Negative is under budget."),
    ])
    left, right = st.columns([3, 2])
    with left:
        show(charts.waste_trend(m.weekly_waste_by_sub_department(scoped)))
    with right:
        show(charts.waste_by_reason(m.waste_by_reason(scoped)))
    left, right = st.columns([3, 2])
    with left:
        show(charts.waste_vs_shelf_life(m.waste_by_product_group(scoped)))
    with right:
        show(charts.waste_by_day(m.waste_by_day(scoped), model.sub_departments))
    st.caption("Waste follows shelf life, so a waste percentage is not comparable across "
               "sub-departments with a different product mix. Compare a sub-department to "
               "itself over time, or like shelf life to like.")

# -------------------------------------------------------- labour and roster

with labour:
    if subs:
        st.info("Labour is recorded by role, not by sub-department, so this page always shows "
                "the whole department for the dates selected.")
    dept = m.headline(dated)
    dept_week = m.weekly(dated)
    cards([
        ("Actual labour cost", money(dept["Actual Labour Cost"]), None),
        ("Labour % of sales", pct(dept["Labour % of Sales"]), None),
        ("Actual vs roster", f"{signed_money(dept['Payroll Variance'])} "
                             f"({pct(dept['Payroll Variance %'], True)})",
         "Payroll variance: actual cost less rostered cost."),
        ("Sales per labour hour", money(dept["Sales per Labour Hour"]), None),
    ])
    left, right = st.columns([3, 2])
    with left:
        show(charts.labour_pct(dept_week))
        show(charts.sales_vs_budget_pct(dept_week))
        st.caption("The weeks where labour percentage spikes are the weeks sales missed budget, "
                   "not the weeks anyone overspent on hours.")
    with right:
        show(charts.hours_by_day(m.hours_by_day(dated)))
        target = st.slider("What if the wage budget were this % of sales?", 9.0, 14.0, 11.65,
                           0.25, format="%.2f%%")
        over = m.weeks_over_scenario(dept_week, target / 100)
        st.metric("Weeks over that budget", f"{over} of {len(dept_week)}",
                  help="Weeks where actual labour cost exceeds sales times the chosen percentage.")
    st.markdown("**The ten weeks with the highest labour %**")
    show_table(
        m.worst_labour_weeks(dept_week).rename(columns={
            "WeekLabel": "Week", "DepartmentSales": "Net sales",
            "SalesVsBudgetPct": "Sales vs budget", "ActualCost": "Labour cost",
            "LabourPct": "Labour % of sales", "PayrollVariance": "Actual vs roster"}),
        ["Labour % of sales"], ["Net sales", "Labour cost"],
        signed_percent=["Sales vs budget"], signed_dollars=["Actual vs roster"])

# ------------------------------------------------------ the ordering change

with change:
    st.markdown(
        f"From **{CHANGE_DATE:%-d %B %Y}**, {' and '.join(CHANGED)} moved to tighter order "
        "quantities and earlier markdowns. The other three sub-departments did not change, "
        "which makes them a control group over the same 52 weeks. This page always uses the "
        "full 104 weeks and ignores the filters.")
    table = m.change_table(model)
    changed = table[table.SubDepartment == "Fruit & Veg + Bakery"].iloc[0]
    control = table[table.SubDepartment == "Control sub-departments"].iloc[0]
    cards([
        ("Waste (changed)", points(changed["Waste % of Sales Change"]),
         f"{pct(changed['Waste % of Sales Before'])} before, "
         f"{pct(changed['Waste % of Sales After'])} after."),
        ("Markdown (changed)", points(changed["Markdown % of Sales Change"]),
         "The cost of marking down earlier."),
        ("Trading margin (changed)", points(changed["Trading Margin % Change"]), None),
        ("Value of the change", money(changed["Value of Change"]),
         f"Margin gain applied to {money(changed['Net Sales After'])} of sales after the change."),
        ("Waste (control)", points(control["Waste % of Sales Change"]),
         "Three sub-departments that did not change."),
    ])
    left, right = st.columns([3, 2])
    with left:
        show(charts.waste_trend(m.weekly_waste_by_sub_department(model), mark_change=True))
    with right:
        show(charts.waste_before_after(table, model.sub_departments))
    columns = {"SubDepartment": "Sub-department", "Group": "Group",
               "Waste % of Sales Before": "Waste % before",
               "Waste % of Sales After": "Waste % after",
               "Waste % of Sales Change": "Waste change",
               "Markdown % of Sales Before": "Markdown % before",
               "Markdown % of Sales After": "Markdown % after",
               "Trading Margin % Change": "Trading margin change"}
    show_table(table[list(columns)].rename(columns=columns),
                  ["Waste % before", "Waste % after", "Markdown % before", "Markdown % after"],
                  [], signed_points=["Waste change", "Trading margin change"])
    st.caption("A waste line trending down proves nothing on its own. A waste line trending "
               "down while three comparable lines hold flat over the same weeks is an argument. "
               "The control group is not randomised, and the data is synthetic: see "
               "docs/FINDINGS.md for what this cannot tell you.")
